import re
base0 = open('build62.py', encoding='utf-8').read()


def make(num, grade, dri, CHs, ROWSs, SC, W, H, head, foot, POOL, UNITS, AREAS, PICK, SW=960):
    s = base0
    s = s.replace("d + 'drive62/poster62.png'", "d + '%s/poster.png'" % dri)
    s = s.replace('초6-2', grade).replace('6-2', grade[1:]).replace('62', num)
    a = s.index('CH = {'); b = s.index('SCENES =')
    s = s[:a] + CHs + '\nOX = 0\nROWS = ' + ROWSs + '\n' + s[b:]
    s = re.sub(r"SCENES = \[\[18, y - 3, 950, h \+ 6\] for y, h, _ in ROWS\]", "SCENES = [[" + SC + ", y - 5, " + str(SW) + ", h + 10] for y, h, _ in ROWS]", s)
    s = s.replace("CELLS = [[[i, x0 - OX, y, x1 - x0, h] for i, x0, x1 in row] for y, h, row in ROWS]",
                  "CELLS = [[[c[0], c[1] - OX, (c[3] if len(c) > 3 else y), c[2] - c[1], ((c[4] - c[3]) if len(c) > 3 else h)] for c in row] for y, h, row in ROWS]")
    s = re.sub(r"POOL = \{.*?\}\n", "POOL = " + POOL + "\n", s, count=1)
    s = re.sub(r"UNITS = \[.*?\]\]\n", "UNITS = " + UNITS + "\n", s, count=1)
    s = re.sub(r"'AREAS': \[.*?\],\n", "'AREAS': " + AREAS + ",\n", s, count=1)
    s = re.sub(r"'PICK': \[.*?\],", "'PICK': " + PICK + ",", s, count=1)
    s = re.sub(r"'width': \d+, 'height': \d+", "'width': %d, 'height': %d" % (W, H), s)
    s = re.sub(r"pic\(\[0,0,A\.width,\d+\],", "pic([0,0,A.width,%d]," % head, s)
    s = re.sub(r"pic\(\[0,\d+,A\.width,\d+\],'강해져라! 수학의 힘!'", "pic([0,%d,A.width,%d],'수학의 힘이 너의 미래를 만든다!'" % foot, s)
    assert 'SCENES = [[' + SC in s and 'c[3] if len(c)' in s
    open('build%s.py' % num, 'w', encoding='utf-8').write(s)


